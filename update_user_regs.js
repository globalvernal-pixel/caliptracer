function parseData(text) {
  const lines = text.split('\n');
  let currentGroup = '';
  const entries = [];

  for (let line of lines) {
    line = line.trim();
    if (!line) continue;
    if (line.startsWith('===')) {
      currentGroup = line.replace(/=/g, '').trim();
      continue;
    }

    const parts = line.split('-');
    if (parts.length >= 2) {
      const regNo = parts[0].trim();
      const name = parts.slice(1).join('-').trim();
      entries.push({ regNo, name, group: currentGroup });
    }
  }
  return entries;
}

function normalize(str) {
  return str.toLowerCase().replace(/[^a-z0-9]/g, '');
}

function words(str) {
  return str.toLowerCase().replace(/[^a-z0-9\s]/g, ' ').split(/\s+/).filter(Boolean);
}

async function runUpdate() {
  const entries = parseData(rawData);
  console.log(`Parsed ${entries.length} student entries.`);

  const allRes = await pool.query('SELECT id, name, class, register_number FROM students');
  const dbStudents = allRes.rows;
  console.log(`Found ${dbStudents.length} total students in database.`);

  let updatedCount = 0;
  let notFoundCount = 0;
  const usedStudentIds = new Set();

  for (const entry of entries) {
    const entryNorm = normalize(entry.name);
    const entryWords = words(entry.name);

    // 1. Exact normalized match
    let match = dbStudents.find(s => !usedStudentIds.has(s.id) && normalize(s.name) === entryNorm);

    // 2. Contains match
    if (!match) {
      match = dbStudents.find(s => {
        if (usedStudentIds.has(s.id)) return false;
        const dbNorm = normalize(s.name);
        return dbNorm.includes(entryNorm) || entryNorm.includes(dbNorm);
      });
    }

    // 3. Word overlap match (at least 2 matching words or 1 unique long word)
    if (!match) {
      match = dbStudents.find(s => {
        if (usedStudentIds.has(s.id)) return false;
        const dbW = words(s.name);
        const overlap = entryWords.filter(w => dbW.includes(w));
        if (overlap.length >= 2) return true;
        if (overlap.length === 1 && overlap[0].length >= 5) return true;
        return false;
      });
    }

    if (match) {
      usedStudentIds.add(match.id);
      await pool.query('UPDATE students SET register_number = $1 WHERE id = $2', [entry.regNo, match.id]);
      updatedCount++;
      console.log(`[MATCH] ${entry.name} (${entry.group}) -> DB "${match.name}" (${match.class}): #${entry.regNo}`);
    } else {
      console.log(`[NOT FOUND] ${entry.name} (${entry.group}) - Reg: ${entry.regNo}`);
      notFoundCount++;
    }
  }

  console.log(`\n================================`);
  console.log(`FINAL RESULTS: ${updatedCount} students updated with 5-digit register numbers!`);
  console.log(`Not matched: ${notFoundCount}`);
  console.log(`================================`);

  await pool.end();
}

runUpdate();
